import {expect,test} from '@playwright/test';
test('correcting a repayment retains its audit trail, original expense and exact unpaid balance',async({page})=>{
 await page.setViewportSize({width:390,height:600});
 await page.addInitScript(()=>sessionStorage.setItem('trip-planner-demo-session','active'));
 await page.route('https://*.supabase.co/**',r=>r.abort());
 await page.goto('./#/12');await expect(page.getByRole('heading',{name:'Budget',exact:true})).toBeVisible();
 await page.evaluate(()=>{const key='trip-planner-demo-v1:demo-maya',s=JSON.parse(localStorage.getItem(key)!);const t=s.trips.find((t:any)=>t.id===s.tripId);const debtor=t.members.find((m:any)=>m.id!==s.userId&&m.status==='accepted').id;t.expenses=[{id:'audit-lunch',purpose:'Audit lunch',amount:2000,category:'Food',payer:s.userId,shares:{[s.userId]:1000,[debtor]:1000},date:s.date,source:'Manual',settled:[]}];localStorage.setItem(key,JSON.stringify(s));});
 await page.reload();await page.getByRole('button',{name:'Repayments',exact:true}).click();
 await page.locator('.repayment-group>summary').click();
 await page.getByRole('button',{name:'Mark paid',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Mark paid',exact:true}).click();
 await expect(page.locator('.repayment-overview')).toContainText('$0.00');
 await page.getByRole('button',{name:'Correct repayment',exact:true}).click();
 const correction=page.getByRole('dialog',{name:'Correct repayment',exact:true});
 await correction.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.locator('.repayment-overview')).toContainText('$0.00');
 await page.getByRole('button',{name:'Correct repayment',exact:true}).click();
 await correction.getByRole('button',{name:'Mark as unpaid',exact:true}).click();
 await expect(correction.getByRole('alert')).toContainText('Enter a reason');
 await expect(page.getByLabel('Reason for correction')).toBeFocused();
 await page.getByLabel('Reason for correction').fill('The transfer was cancelled.');
 await page.screenshot({path:test.info().outputPath('repayment-correction-phone.png')});
 await correction.getByRole('button',{name:'Mark as unpaid',exact:true}).click();
 await expect(page.locator('.repayment-overview')).toContainText('$10.00');
 await page.reload();await page.getByRole('button',{name:'Repayments',exact:true}).click();await page.locator('.repayment-group>summary').click();
 await page.getByText('Repayment history',{exact:true}).click();
 await expect(page.locator('.repayment-history')).toContainText('Marked paid');
 await expect(page.locator('.repayment-history')).toContainText('Corrected to unpaid');
 await expect(page.locator('.repayment-history')).toContainText('The transfer was cancelled.');
 await page.getByRole('button',{name:/Expense log/}).click();await page.getByRole('button',{name:'Details',exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('cannot be changed');
 await expect(page.getByRole('dialog').getByRole('button',{name:'Save expense'})).toHaveCount(0);
 const saved=await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('trip-planner-demo-v1:demo-maya')!);return s.trips.find((t:any)=>t.id===s.tripId).expenses[0];});
 expect(saved.amount).toBe(2000);expect(saved.settled).toHaveLength(1);expect(saved.repaymentHistory.map((e:any)=>e.status)).toEqual(['paid','unpaid']);
});
